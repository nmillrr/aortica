#!/usr/bin/env python3
"""Render a release's evaluation JSON into RESULTS.md and headline numbers.

Reads, from a release directory such as ``releases/v0.4.0``:

* ``test_metrics.json`` and ``run_manifest.json`` (``train_reference.py``)
* ``evaluation/external_georgia.json`` (``external_validation.py``)
* ``evaluation/baseline_ribeiro.json`` (``compare_baseline.py``)

and writes ``RESULTS.md`` beside them, so every table quoted in the README,
the landing page or a paper is generated from the same files.  With
``--fill FILE ...`` it also substitutes ``{{PLACEHOLDER}}`` tokens in those
files with the headline numbers.

Usage::

    python scripts/render_results.py releases/v0.4.0 --fill README.md landing/index.html
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

PRIMARY = "v0.4.0 reference (PyTorch)"


def _f(x: Optional[float], nd: int = 3) -> str:
    return "—" if x is None else f"{x:.{nd}f}"


def _ci(ci: Optional[Sequence[float]], nd: int = 3) -> str:
    return "" if not ci else f" ({ci[0]:.{nd}f}–{ci[1]:.{nd}f})"


def _auc_cell(r: Optional[Dict[str, Any]]) -> str:
    if not r or r.get("auroc") is None:
        return "—"
    return f"{r['auroc']:.3f}{_ci(r.get('auroc_ci95'))}"


def render(release: Path) -> tuple[str, Dict[str, str]]:
    test = json.loads((release / "test_metrics.json").read_text())
    manifest = json.loads((release / "run_manifest.json").read_text())
    thresholds = json.loads((release / "class_thresholds.json").read_text())
    ext_path = release / "evaluation" / "external_georgia.json"
    base_path = release / "evaluation" / "baseline_ribeiro.json"
    ext = json.loads(ext_path.read_text()) if ext_path.exists() else None
    base = json.loads(base_path.read_text()) if base_path.exists() else None
    trained: List[str] = json.loads((release / "trained_outputs.json").read_text())[
        "trained_outputs"]

    out: List[str] = []
    w = out.append
    w(f"# Aortica {manifest['version']} — results\n")
    w("Generated by `scripts/render_results.py` from the JSON files in this directory; "
      "edit those, not this file.\n")
    w("Macro-AUROC is the mean over trained classes with at least the stated number of "
      "test positives. 95% intervals are percentile bootstrap over records. Operating "
      "points (`class_thresholds.json`) were tuned on the validation splits only and are "
      "applied unchanged everywhere below.\n")

    # ── Summary ──────────────────────────────────────────────────────────
    w("## Summary\n")
    w("| Cohort | Role | ECGs | Macro-AUROC (≥10 pos) | Classes | Macro-AUROC (≥1 pos) | Classes |")
    w("|---|---|---:|---|---:|---|---:|")
    head: Dict[str, str] = {}
    for corpus, label in (("ptbxl", "PTB-XL fold 10"), ("chapman", "Chapman test split")):
        s = test["summary"][corpus]
        w(f"| {label} | internal test | {s['n_records']:,} | "
          f"{_f(s['macro_auroc_min10pos'])} | {s['n_classes_min10pos']} | "
          f"{_f(s['macro_auroc'])}{_ci(s.get('macro_auroc_ci95'))} | {s['n_classes']} |")
        head[f"{corpus.upper()}_AUROC"] = _f(s["macro_auroc_min10pos"])
        head[f"N_{corpus.upper()}"] = f"{s['n_records']:,}"
    if ext:
        m = ext["models"][PRIMARY]
        m10, m1 = m["macro_auroc_min10pos"], m["macro_auroc_min1pos"]
        n = ext["cohort"]["n_records"]
        w(f"| Georgia (PhysioNet 2021) | **external** | {n:,} | "
          f"{_f(m10['value'])}{_ci(m10['ci95'])} | {m10['n_classes']} | "
          f"{_f(m1['value'])}{_ci(m1['ci95'])} | {m1['n_classes']} |")
        head["GEORGIA_AUROC"] = _f(m10["value"])
        head["GEORGIA_AUROC_CI"] = _ci(m10["ci95"]).strip(" ()")
        head["N_GEORGIA"] = f"{n:,}"
    head["N_TRAIN"] = f"{manifest['records']['train']:,}"
    w("")

    # ── Internal per-class ───────────────────────────────────────────────
    w("## Internal test sets, per class\n")
    w("| Output | Threshold | PTB-XL n+ | PTB-XL AUROC | PTB-XL F1 | Chapman n+ | "
      "Chapman AUROC | Chapman F1 |")
    w("|---|---:|---:|---|---:|---:|---|---:|")
    for name in trained:
        p, c = test.get(f"ptbxl/{name}"), test.get(f"chapman/{name}")
        w(f"| {name} | {thresholds.get(name, 0.5):.2f} | "
          f"{p['n_pos'] if p else '—'} | {_auc_cell(p)} | {_f(p and p.get('f1'))} | "
          f"{c['n_pos'] if c else '—'} | {_auc_cell(c)} | {_f(c and c.get('f1'))} |")
    w("\n`—`: the corpus cannot label this output. AUROC with fewer than 10 positives "
      "is shown without an interval and should not be relied on.\n")

    # ── External ─────────────────────────────────────────────────────────
    if ext:
        w("## External validation — Georgia\n")
        w(f"{ext['cohort']['name']}. {ext['protocol']} Labels: "
          f"`{ext['cohort']['label_map']}`.\n")
        models = list(ext["models"])
        w("### Macro-AUROC by model\n")
        w("| Model | ≥10 pos | ≥1 pos |")
        w("|---|---|---|")
        for name in models:
            m = ext["models"][name]
            w(f"| {name} | {_f(m['macro_auroc_min10pos']['value'])}"
              f"{_ci(m['macro_auroc_min10pos']['ci95'])} | "
              f"{_f(m['macro_auroc_min1pos']['value'])}{_ci(m['macro_auroc_min1pos']['ci95'])} |")
        w("")
        w(f"### Per class ({PRIMARY}, at frozen thresholds)\n")
        w("| Output | n+ | AUROC | AUPRC | Sensitivity | Specificity | PPV | "
          "v0.3.0 INT8 AUROC |")
        w("|---|---:|---|---:|---:|---:|---:|---|")
        prim = ext["models"][PRIMARY]["per_class"]
        int8 = ext["models"].get("v0.3.0 edge INT8 (ONNX)", {}).get("per_class", {})
        for name, r in sorted(prim.items(), key=lambda kv: -kv[1]["n_pos"]):
            if r["n_pos"] == 0:
                continue
            w(f"| {name} | {r['n_pos']} | {_auc_cell(r)} | {_f(r['auprc'])} | "
              f"{_f(r['sensitivity'])} | {_f(r['specificity'])} | {_f(r['ppv'])} | "
              f"{_auc_cell(int8.get(name))} |")
        zero = sorted(n for n, r in prim.items() if r["n_pos"] == 0)
        if zero:
            w(f"\nNo Georgia positives (not scored): {', '.join(zero)}.\n")
        w("### Subgroups (macro-AUROC, ≥10 positives within subgroup)\n")
        w("| Subgroup | ECGs | Macro-AUROC | Classes |")
        w("|---|---:|---|---:|")
        for g, v in ext["models"][PRIMARY]["subgroups"].items():
            w(f"| {g} | {v['n_records']:,} | {_f(v['macro_auroc_min10pos'])} | "
              f"{v['n_classes']} |")
        w("\n### Sensitivity analysis — incomplete bundle branch block counted as positive\n")
        w("PTB-XL's training labels pool incomplete RBBB/LBBB into RBBB/LBBB; Georgia's "
          "primary definition (and Chapman's) does not.\n")
        w("| Output | Definition | n+ | AUROC | Sensitivity | Specificity |")
        w("|---|---|---:|---|---:|---:|")
        alt = ext["models"][PRIMARY]["sensitivity_incomplete_bbb_positive"]
        for name in ("RBBB", "LBBB"):
            for label, r in (("complete only", prim[name]), ("incl. incomplete", alt[name])):
                w(f"| {name} | {label} | {r['n_pos']} | {_auc_cell(r)} | "
                  f"{_f(r['sensitivity'])} | {_f(r['specificity'])} |")
        w("")

    # ── Baseline ─────────────────────────────────────────────────────────
    if base:
        w("## Baseline — Ribeiro et al. (2020)\n")
        sel = base["selection"]
        w(f"{base['baseline']}. Preprocessing selected on PTB-XL validation fold 9: lead "
          f"order `{sel['lead_order']}`, scale `{sel['scale']}`, padding `{sel['padding']}` "
          "(see `_work/ribeiro/ribeiro_preprocessing_selection.json`). Ground truth uses "
          "complete-block definitions from each cohort's source codes. Δ = Aortica − "
          "Ribeiro, paired bootstrap 95% CI.\n")
        for cohort, body in base["cohorts"].items():
            w(f"### {cohort} — {body['role']} (n = {body['n_records']:,})\n")
            w("| Finding | n+ | Aortica AUROC | Ribeiro AUROC | Δ AUROC | Aortica AUPRC | "
              "Ribeiro AUPRC | Δ AUPRC |")
            w("|---|---:|---:|---:|---|---:|---:|---|")
            for r, v in body["per_class"].items():
                w(f"| {r} ({v['aortica_output']}) | {v['n_pos']} | {_f(v['aortica_auroc'])} | "
                  f"{_f(v['ribeiro_auroc'])} | {v['delta_auroc']:+.3f}"
                  f"{_ci(v['delta_auroc_ci95'])} | {_f(v['aortica_auprc'])} | "
                  f"{_f(v['ribeiro_auprc'])} | {v['delta_auprc']:+.3f}"
                  f"{_ci(v['delta_auprc_ci95'])} |")
            w(f"| **Mean** | | **{_f(body['mean_auroc']['aortica'])}** | "
              f"**{_f(body['mean_auroc']['ribeiro'])}** | | "
              f"**{_f(body['mean_auprc']['aortica'])}** | "
              f"**{_f(body['mean_auprc']['ribeiro'])}** | |")
            w("")
        g = base["cohorts"]["georgia"]
        head["BASELINE_A"] = _f(g["mean_auroc"]["aortica"])
        head["BASELINE_R"] = _f(g["mean_auroc"]["ribeiro"])

    # ── Provenance ───────────────────────────────────────────────────────
    w("## Provenance\n")
    w(f"- Config: `config.yaml`; seed {manifest['seed']}; best epoch "
      f"{manifest['best_epoch']} by masked validation loss")
    w(f"- Commit `{manifest['git_commit'][:12]}` (dirty at start: {manifest['git_dirty']})")
    w(f"- torch {manifest['torch']}, numpy {manifest['numpy']}, scipy {manifest['scipy']}, "
      f"Python {manifest['python']}, {manifest['torch_threads']} threads, "
      f"{manifest['platform']}")
    w(f"- Weights `{manifest['weights_file']}` SHA-256 `{manifest['weights_sha256']}`")
    w(f"- Splits `splits.csv` SHA-256 `{manifest['splits_sha256']}`")
    w(f"- Records — train {manifest['records']['train']:,}, val "
      f"{manifest['records']['val']:,}, test {manifest['records']['test']:,}")
    w("")
    return "\n".join(out), head


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("release", type=Path)
    ap.add_argument("--fill", nargs="*", type=Path, default=[],
                    help="Files whose {{PLACEHOLDER}} tokens to fill in place")
    ap.add_argument("--baseline-sentence", default=None,
                    help="Override the {{BASELINE_SENTENCE}} text")
    args = ap.parse_args(argv)

    text, head = render(args.release)
    (args.release / "RESULTS.md").write_text(text)
    if args.baseline_sentence:
        head["BASELINE_SENTENCE"] = args.baseline_sentence
    print(json.dumps(head, indent=2))
    for path in args.fill:
        s = path.read_text()
        for k, v in head.items():
            s = s.replace("{{" + k + "}}", v)
        left = sorted(set(re.findall(r"{{([A-Z0-9_]+)}}", s)))
        path.write_text(s)
        print(f"filled {path}" + (f" — unfilled: {left}" if left else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
